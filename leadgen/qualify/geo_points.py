RUSSIA_NAMES = {'russia', 'россия', 'российская федерация', 'russian federation'}


def _km(a, b):
    lat1, lng1, lat2, lng2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = (math.sin((lat2 - lat1) / 2) ** 2
         + math.cos(lat1) * math.cos(lat2) * math.sin((lng2 - lng1) / 2) ** 2)
    return 6371 * 2 * math.asin(math.sqrt(h))


def classify(loc):
    """('ru', city | None) | ('foreign', None) | ('unknown', None) for a single location tag."""
    if not loc or loc.get('lat') is None or loc.get('lng') is None:
        return 'unknown', None
    if (loc.get('name') or '').strip().lower() in RUSSIA_NAMES:
        return 'ru', None
    point = (float(loc['lat']), float(loc['lng']))
    city, dist = min(((c, _km(point, xy)) for c, xy in CITY_COORDS.items()), key=lambda cd: cd[1])
    anchor = min(_km(point, xy) for xy in FOREIGN_ANCHORS.values())
    if anchor < dist and anchor < NEAR_KM * 1.5:
        return 'foreign', None
    if dist <= NEAR_KM:
        return 'ru', city
    if dist > FAR_KM:
        return 'foreign', None
    return 'unknown', None


def verdict(locs):
    """Overall verdict across a profile's post location tags: ('ru', city | None) |
    ('foreign', None) | ('none', None). A city is returned only if at least two tags
    point to it."""
    marks = [classify(l) for l in locs if l]
    if not marks:
        return 'none', None
    foreign = sum(1 for kind, _ in marks if kind == 'foreign')
    ru = [city for kind, city in marks if kind == 'ru']
    if foreign >= 2 and foreign >= 0.6 * len(marks):
        return 'foreign', None
    if ru:
        cities = Counter(c for c in ru if c)
        top = cities.most_common(1)
        return 'ru', (top[0][0] if top and top[0][1] >= 2 else None)
    return 'none', None


def names(locs):
    """Names of the foreign location tags — used for the rejection reason."""
    out = []
    for l in locs:
        if l and classify(l)[0] == 'foreign' and (l.get('name') or '') not in out:
            out.append(l.get('name') or '')
    return [n for n in out if n]
